// - `carbs` = available carbohydrates (EU / CIQUAL convention: fiber is NOT
//   included in carbs). Energy ≈ 4·protein + 4·carbs + 9·fat + 2·fiber.
// - Single ingredients follow USDA FoodData Central (SR Legacy) and the French
